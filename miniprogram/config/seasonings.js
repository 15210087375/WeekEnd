const _kwSorted = SEASONING_KEYWORDS.slice()
  .filter(Boolean)
  .sort((a, b) => b.length - a.length);

const _mainSorted = MAIN_FORCE_KEYWORDS.slice()
  .filter(Boolean)
  .sort((a, b) => b.length - a.length);

function compactText(s) {
  return String(s || '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '')
    .replace(/[，,、/|·.。:：;；()（）【】\[\]{}]/g, '');
}

/**
 * 去掉用量描述，便于关键词命中「盐少许」「生抽 1 勺」
 */
function stripQuantity(compact) {
  return compact
    .replace(/[0-9]+\.?[0-9]*/g, '')
    .replace(
      /(千克|公斤|克|两|钱|斤|毫升|升|mg|g|kg|ml|l|大勺|小勺|茶匙|汤匙|勺|匙|杯|碗|个|只|根|片|颗|粒|把|条|块|滴|适量|少许|若干|一点点|一点|一些|半|整|约|左右|许)/gi,
      ''
    );
}

/**
 * @param {string} line 用料原文
 * @returns {boolean} 是否判为调料
 */
function isSeasoningLine(line) {
  const c = compactText(line);
  if (!c) return false;

  for (let i = 0; i < _mainSorted.length; i++) {
    if (c.indexOf(_mainSorted[i].toLowerCase()) >= 0) return false;
  }

  const core = stripQuantity(c);
  const hay = core.length >= 1 ? core : c;

  for (let i = 0; i < _kwSorted.length; i++) {
    const kw = _kwSorted[i].toLowerCase();
    if (c.indexOf(kw) >= 0 || hay.indexOf(kw) >= 0) return true;
  }
  return false;
}

/**
 * @param {string} line
 * @returns {'seasoning'|'main'}
 */
function classifyIngredientLine(line) {
  return isSeasoningLine(line) ? 'seasoning' : 'main';
}

